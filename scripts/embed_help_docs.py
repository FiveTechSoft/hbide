#!/usr/bin/env python3
"""Embed every tracked Markdown document in the offline Harbour manual.
Run after documentation edits; --check fails on a stale generated catalogue.
No network, third-party modules or build-time Python dependency.
"""
import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'helpdocs.ch'

def generate():
    paths = subprocess.check_output(['git', 'ls-files', '*.md'], cwd=ROOT, text=True).splitlines()
    groups = {'6. Complete manuals': [], '7. Technical reference': [], '8. Checkpoints and plans': []}
    chunks = ['// Generated by scripts/embed_help_docs.py. Do not edit.\n', 'FUNCTION HBIDEHelpDocTopics()\n   LOCAL a := {}\n']
    for path in paths:
        text = (ROOT / path).read_text()
        title = 'Doc: ' + (Path(path).stem if Path(path).stem != 'README' else str(Path(path).parent) + ' index')
        if path == 'README.md':
            title = 'Doc: hbide overview'
        group = '6. Complete manuals' if path in ['README.md', 'docs/README.md', 'docs/quickstart.md', 'docs/user-guide.md', 'docs/designer.md'] else ('8. Checkpoints and plans' if any(x in path.lower() for x in ['checkpoint', 'verification', 'validation', 'roadmap', 'repaint']) else '7. Technical reference')
        groups[group].append(title)
        # Each body is the exact UTF-8 file, preceded by provenance. Quoted
        # hex avoids any Harbour preprocessor/string escaping ambiguities.
        body = 'Source: ' + path + '\nRepository snapshot; dated checkpoints are historical.\n\n' + text
        pieces = ['hb_HexToStr( "' + body.encode()[i:i+1000].hex() + '" )' for i in range(0, len(body.encode()), 1000)]
        chunks.append('   AAdd( a, { "' + path + '", "' + title + '", ;\n      ' + ' + ;\n      '.join(pieces) + ' } )\n')
    chunks.append('RETURN a\n\nFUNCTION HBIDEHelpDocSections()\nRETURN { ')
    chunks.append(', ;\n         '.join('{ "' + g + '", { ' + ', '.join('"' + t + '"' for t in ts) + ' } }' for g, ts in groups.items()))
    chunks.append(' }\n')
    return ''.join(chunks), len(paths)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != content:
            raise SystemExit('Stale helpdocs.ch: run python3 scripts/embed_help_docs.py')
        print(f'PASS: {count} complete documents embedded byte-for-byte')
    else:
        OUT.write_text(content)
        print(f'Embedded {count} complete documents in {OUT.name}')
